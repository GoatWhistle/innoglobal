import {chromium} from '../../../frontend/node_modules/playwright/index.mjs'
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
page.setDefaultTimeout(12000);
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto(process.env.E2E_BASE_URL ?? 'http://127.0.0.1:5191')
await page.getByRole('button',{name:'Карта',exact:true}).click()
await page.getByRole('button',{name:'К трубам',exact:true}).click()
await page.screenshot({path:'work/audits/react-port/map-local.png'})
await page.getByRole('link',{name:'Перейти к трубе'}).click()
await page.getByLabel('Номер участка',{exact:true}).fill('20')
await page.getByLabel('Номер участка',{exact:true}).press('Enter')
await page.mouse.move(10,10)
await page.waitForTimeout(6500)
await page.screenshot({path:'work/audits/react-port/inspection-dark.png'})
await page.getByRole('button',{name:'Ассистент',exact:true}).click()
await page.getByRole('button',{name:/Объясни приоритет/}).click()
await page.getByTestId('assistant-answer').filter({hasText:'Приоритет проверки не означает'}).waitFor()
await page.screenshot({path:'work/audits/react-port/chat-dark.png'})
await page.getByRole('button',{name:'Переместить чат'}).click()
await page.screenshot({path:'work/audits/react-port/chat-left.png'})
console.log('chat',await page.getByTestId('assistant-answer').innerText())
