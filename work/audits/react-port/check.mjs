await page.mouse.move(10,10)
if(!page.url().includes('view=unroll'))throw Error('Changed view')
await page.screenshot({path:'work/audits/react-port/unroll-dark.png',fullPage:true})
await page.getByRole('radio',{name:'Светлая тема',exact:true}).click()
await page.screenshot({path:'work/audits/react-port/unroll-light.png',fullPage:true})
await page.setViewportSize({width:375,height:812})
await page.screenshot({path:'work/audits/react-port/mobile-light.png',fullPage:true})
console.log('overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))
console.log('errors',errors)
